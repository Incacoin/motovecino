-- Un chofer, un solo viaje activo. Con SQLite esto lo garantizaba que todo
-- corría en fila; con Postgres dos "aceptar" pueden llegar al mismo tiempo,
-- y este índice hace que el segundo falle (rides.js lo convierte en 409).
CREATE UNIQUE INDEX IF NOT EXISTS idx_rides_one_active_per_driver ON rides(driver_id)
  WHERE status IN ('aceptado', 'llegue', 'en_curso');

