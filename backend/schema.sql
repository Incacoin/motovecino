-- Esquema de MotoVecino en Postgres. Corre en cada arranque (db.init): todo es
-- "IF NOT EXISTS" / "OR REPLACE", así que repetirlo no cambia nada.
--
-- Las fechas siguen guardándose como TEXTO en UTC ('YYYY-MM-DD HH:MM:SS'),
-- igual que en SQLite: así las apps, los respaldos viejos y las comparaciones
-- de texto ("cooldown_until <= ahora") se comportan exactamente igual.
-- Columnas nuevas: agregarlas abajo con ALTER TABLE ... ADD COLUMN IF NOT EXISTS.

-- ---------- Funciones de fecha con el mismo comportamiento que SQLite ----------
-- El código sigue escribiendo datetime('now', '-6 hours'), date(x, 'start of
-- month'), julianday(x)...; db.js cambia datetime( → sl_datetime( y
-- date( → sl_date( (date() choca con el tipo date de Postgres).

CREATE OR REPLACE FUNCTION sl_ts(t text, mods text[]) RETURNS timestamp
LANGUAGE plpgsql STABLE AS $$
DECLARE
  ts timestamp;
  m text;
BEGIN
  IF t IS NULL THEN RETURN NULL; END IF;
  IF lower(t) = 'now' THEN
    ts := date_trunc('second', now() AT TIME ZONE 'UTC');
  ELSE
    BEGIN
      ts := t::timestamp;
    EXCEPTION WHEN others THEN
      RETURN NULL; -- SQLite regresa NULL con una fecha que no entiende
    END;
  END IF;
  FOREACH m IN ARRAY coalesce(mods, '{}') LOOP
    m := lower(trim(m));
    IF m = 'start of month' THEN
      ts := date_trunc('month', ts);
    ELSIF m = 'start of day' THEN
      ts := date_trunc('day', ts);
    ELSIF m = 'start of year' THEN
      ts := date_trunc('year', ts);
    ELSIF m ~ '^weekday [0-6]$' THEN
      -- Avanza al siguiente día con ese número (0 = domingo); si ya lo es, se queda.
      ts := ts + ((substr(m, 9)::int - extract(dow FROM ts)::int + 7) % 7) * interval '1 day';
    ELSIF m ~ '^[+-]?[0-9]+(\.[0-9]+)? *(second|minute|hour|day|month|year)s?$' THEN
      ts := ts + m::interval;
    ELSE
      RETURN NULL;
    END IF;
  END LOOP;
  RETURN ts;
END $$;

CREATE OR REPLACE FUNCTION sl_datetime(t text, VARIADIC mods text[] DEFAULT '{}') RETURNS text
LANGUAGE sql STABLE AS $$ SELECT to_char(sl_ts(t, mods), 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE OR REPLACE FUNCTION sl_date(t text, VARIADIC mods text[] DEFAULT '{}') RETURNS text
LANGUAGE sql STABLE AS $$ SELECT to_char(sl_ts(t, mods), 'YYYY-MM-DD') $$;

CREATE OR REPLACE FUNCTION julianday(t text) RETURNS double precision
LANGUAGE sql STABLE AS $$ SELECT extract(epoch FROM sl_ts(t, '{}'))::double precision / 86400 + 2440587.5 $$;

-- ROUND(real, 2) existe en SQLite; en Postgres solo para numeric.
CREATE OR REPLACE FUNCTION round(double precision, integer) RETURNS double precision
LANGUAGE sql IMMUTABLE AS $$ SELECT round($1::numeric, $2)::double precision $$;

